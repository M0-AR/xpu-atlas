"""Render simulation results as CSV, Markdown, and a Pareto figure."""

from __future__ import annotations

from pathlib import Path

CSV_FIELDS = [
    "workload_id",
    "architecture_id",
    "family",
    "pareto",
    "latency_ms",
    "throughput_tops",
    "energy_j",
    "average_power_w",
    "area_mm2",
    "cost_usd",
    "perf_per_w_tops",
    "perf_per_dollar_tops",
    "peak_utilization",
    "bottleneck",
]

FAMILY_COLORS = {
    "CPU baseline": "#2c3e50",
    "GPU baseline": "#16a085",
    "NPU baseline": "#d35400",
    "Sparse event": "#2980b9",
    "Stochastic": "#8e44ad",
    "Memory-centric": "#27ae60",
    "Photonic": "#e67e22",
    "In-memory": "#c0392b",
    "Hybrid": "#7f8c8d",
}


def _fmt(value: float, digits: int = 3) -> str:
    return f"{value:.{digits}f}"


def _fmt_sci(value: float, digits: int = 2) -> str:
    return f"{value:.{digits}e}"


def result_rows(payload: dict) -> list[dict]:
    rows = []
    for result in payload["results"]:
        metrics = result["metrics"]
        rows.append(
            {
                "workload_id": result["workload_id"],
                "architecture_id": result["architecture_id"],
                "family": result["family"],
                "pareto": result["pareto"],
                "latency_ms": round(metrics["latency_ms"], 6),
                "throughput_tops": round(metrics["throughput_tops"], 6),
                "energy_j": round(metrics["energy_j"], 9),
                "average_power_w": round(metrics["average_power_w"], 6),
                "area_mm2": round(metrics["area_mm2"], 3),
                "cost_usd": round(metrics["cost_usd"], 3),
                "perf_per_w_tops": round(metrics["perf_per_w_tops"], 6),
                "perf_per_dollar_tops": round(metrics["perf_per_dollar_tops"], 6),
                "peak_utilization": round(metrics["peak_utilization"], 6),
                "bottleneck": metrics["bottleneck"],
            }
        )
    return rows


def render_markdown(payload: dict) -> str:
    metadata = payload["metadata"]
    lines = [
        "# Design-Space Simulation",
        "",
        "Generated by `python -m sim.run` from the analytical model in `sim/`. "
        "The simulator screens hypothetical architectures; it does not measure "
        "silicon, and it does not turn a model result into an evidence claim.",
        "",
        "> **Scope:** these are assumptions at a shared reference node. "
        "The next gate is iso-accuracy validation, then RTL or FPGA prototyping.",
        "",
        "## Model",
        "",
        "| Assumption | Value |",
        "|---|---|",
        f"| Reference node | {metadata['reference_node_nm']} nm |",
        f"| Reference clock | {metadata['reference_clock_ghz']:.1f} GHz |",
        f"| Cost model | ${metadata['cost_per_mm2_usd']:.2f}/mm² + ${metadata['package_cost_usd']:.2f} package |",
        "| Compute time | effective ops / (peak ops × workload utilization) |",
        "| Memory time | bytes moved / peak bandwidth |",
        "| Interconnect time | communication bytes / peak interconnect bandwidth |",
        "| Latency | max(compute, memory, interconnect) × mapping overhead + fixed latency + dependency |",
        "| Energy | ops × energy/op + bytes × energy/byte + communication × energy/comm-byte |",
        "",
        "The utilization and overhead multipliers encode workload-to-structure fit. "
        "They are the most important sensitivity knobs, not measured constants.",
        "",
        "## Design space",
        "",
        "| Axis | Values |",
        "|---|---|",
    ]
    for axis, values in payload["axes"].items():
        lines.append(f"| `{axis}` | {', '.join(values)} |")
    lines += [
        "",
        f"Cartesian space: **{metadata['design_space_size']:,}** combinations. "
        f"Evaluated in this sprint: **{metadata['evaluated_candidates']}** candidates × "
        f"**{metadata['workloads']}** workloads = **{metadata['experiments']}** experiments.",
        "",
        "## Workloads",
        "",
        "| ID | Workload | Effective ops | Bytes moved | Communication | Sparsity | Bottleneck |",
        "|---|---|---:|---:|---:|---:|---|",
    ]
    for workload in payload["workloads"]:
        lines.append(
            f"| `{workload['id']}` | {workload['name']} | "
            f"{workload['ops'] / 1e9:.2f}G | {workload['bytes_moved'] / 1e6:.1f}MB | "
            f"{workload['communication_bytes'] / 1e6:.1f}MB | "
            f"{100 * workload['sparsity']:.0f}% | {workload['bottleneck']} |"
        )
    lines += [
        "",
        "## Candidates",
        "",
        "| ID | Family | Execution | Memory | Dataflow | Interconnect | Numeric | Programming |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for architecture in payload["architectures"]:
        lines.append(
            f"| `{architecture['id']}` | {architecture['family']} | "
            f"{architecture['execution']} | {architecture['memory']} | "
            f"{architecture['dataflow']} | {architecture['interconnect']} | "
            f"{architecture['numeric']} | {architecture['programming']} |"
        )
    lines += ["", "## Results", ""]
    for workload in payload["workloads"]:
        subset = [
            result
            for result in payload["results"]
            if result["workload_id"] == workload["id"]
        ]
        subset.sort(key=lambda result: (not result["pareto"], result["metrics"]["latency_ms"]))
        lines += [
            f"### {workload['name']}",
            "",
            workload["description"],
            "",
            "| Architecture | Family | Latency (ms) | Throughput (TOPS) | Energy (J) | Power (W) | Cost ($) | TOPS/W | TOPS/$ | Pareto |",
            "|---|---|---:|---:|---:|---:|---:|---:|---:|---|",
        ]
        for result in subset:
            metrics = result["metrics"]
            lines.append(
                f"| `{result['architecture_id']}` | {result['family']} | "
                f"{_fmt(metrics['latency_ms'])} | {_fmt(metrics['throughput_tops'])} | "
                f"{_fmt_sci(metrics['energy_j'])} | {_fmt(metrics['average_power_w'])} | "
                f"{_fmt(metrics['cost_usd'])} | {_fmt(metrics['perf_per_w_tops'])} | "
                f"{_fmt(metrics['perf_per_dollar_tops'])} | "
                f"{'yes' if result['pareto'] else ''} |"
            )
        lines += [
            "",
            f"Frontier: {', '.join(f'`{item}`' for item in payload['frontier'][workload['id']])}.",
            "",
        ]
    lines += [
        "## Cross-workload summary",
        "",
        "| Architecture | Family | Pareto workloads |",
        "|---|---|---:|",
    ]
    for architecture in payload["architectures"]:
        appearances = payload["summary"]["pareto_appearances"].get(architecture["id"], 0)
        lines.append(
            f"| `{architecture['id']}` | {architecture['family']} | {appearances} |"
        )
    lines += [
        "",
        "| Workload | Best latency | Best energy | Best cost |",
        "|---|---|---|---|",
    ]
    for workload in payload["workloads"]:
        best = payload["summary"]["best_by_workload"][workload["id"]]
        lines.append(
            f"| `{workload['id']}` | `{best['latency']}` | `{best['energy']}` | "
            f"`{best['cost']}` |"
        )
    lines += [
        "",
        "## Reading the result",
        "",
        "- The frontier is workload-specific. A design that wins on one workload "
        "is not a universal replacement for a CPU, GPU, or NPU.",
        "- A Pareto marker means no other evaluated candidate is better on latency "
        "and energy at the same time. Cost and area are reported separately and are "
        "not part of the frontier test. It does not mean the design is buildable.",
        "- The baseline rows are deliberately conservative placeholders. Replace "
        "them with measured baselines before making procurement or investment claims.",
        "- Accuracy is a gate, not a simulated metric. A candidate must first match "
        "the baseline's accuracy on the target workload.",
        "",
        "## Limitations",
        "",
        "- Analytical roofline, not cycle-accurate simulation.",
        "- No SRAM capacity, NoC contention, yield, packaging, thermal, or compiler "
        "effects are modelled.",
        "- No accuracy or numerical-stability measurement.",
        "- The candidate list is a hand-pruned sample of a much larger design space.",
        "- All numbers are assumptions at one reference node; they are not predictions.",
        "",
        "## Reproduce",
        "",
        "```bash",
        "make sim",
        "# writes results/simulation.json, results/simulation.csv,",
        "# docs/SIMULATION.md, and figures/fig7_design_space.png",
        "```",
        "",
    ]
    return "\n".join(lines)


def plot_design_space(payload: dict, path: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams.update(
        {
            "figure.dpi": 200,
            "savefig.dpi": 200,
            "font.family": "DejaVu Sans",
            "font.size": 9,
            "axes.titlesize": 9,
            "axes.labelsize": 8,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "axes.grid": True,
            "grid.alpha": 0.25,
            "grid.linewidth": 0.6,
            "legend.frameon": False,
            "figure.facecolor": "white",
            "axes.facecolor": "white",
        }
    )

    workloads = payload["workloads"]
    figure, axes = plt.subplots(1, len(workloads), figsize=(13.0, 4.4))
    handles: dict[str, object] = {}

    for axis, workload in zip(axes, workloads):
        subset = [
            result
            for result in payload["results"]
            if result["workload_id"] == workload["id"]
        ]
        for result in subset:
            metrics = result["metrics"]
            color = FAMILY_COLORS.get(result["family"], "#7f8c8d")
            marker = "s" if "baseline" in result["family"] else "o"
            axis.scatter(
                metrics["latency_ms"],
                metrics["energy_j"],
                s=70 if result["pareto"] else 28,
                marker=marker,
                color=color,
                edgecolors="#111111" if result["pareto"] else "white",
                linewidths=1.0 if result["pareto"] else 0.4,
                alpha=0.95 if result["pareto"] else 0.55,
                zorder=3 if result["pareto"] else 2,
            )
            if result["family"] not in handles:
                handles[result["family"]] = axis.scatter([], [], marker=marker, color=color)
            if result["pareto"]:
                axis.annotate(
                    result["architecture_id"],
                    (metrics["latency_ms"], metrics["energy_j"]),
                    textcoords="offset points",
                    xytext=(4, 3),
                    fontsize=6,
                    color="#222222",
                )
        axis.set_xscale("log")
        axis.set_yscale("log")
        axis.set_title(workload["name"])
        axis.set_xlabel("Latency (ms, log scale)")
        if axis is axes[0]:
            axis.set_ylabel("Energy per workload (J, log scale)")

    figure.legend(
        handles.values(),
        handles.keys(),
        loc="lower center",
        ncol=5,
        fontsize=7,
        markerscale=0.8,
    )
    figure.suptitle(
        "Analytical design-space screening at 5 nm / 1 GHz — not silicon measurements",
        fontsize=11,
        y=1.02,
    )
    figure.tight_layout(rect=(0, 0.08, 1, 0.98))
    path.parent.mkdir(parents=True, exist_ok=True)
    figure.savefig(path, bbox_inches="tight")
    plt.close(figure)
