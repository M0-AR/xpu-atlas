def _arch(
    *,
    id: str,
    name: str,
    family: str,
    execution: str,
    memory: str,
    dataflow: str,
    interconnect: str,
    numeric: str,
    programming: str,
    peak_ops_s: float,
    bandwidth_bytes_s: float,
    interconnect_bytes_s: float,
    energy_per_op_pj: float,
    energy_per_byte_pj: float,
    energy_per_comm_byte_pj: float,
    area_mm2: float,
    fixed_latency_us: float,
    utilization: tuple[float, float, float],
    overhead: tuple[float, float, float],
    note: str,
) -> Architecture:
    return Architecture(
        id=id,
        name=name,
        family=family,
        execution=execution,
        memory=memory,
        dataflow=dataflow,
        interconnect=interconnect,
        numeric=numeric,
        programming=programming,
        peak_ops_s=peak_ops_s,
        bandwidth_bytes_s=bandwidth_bytes_s,
        interconnect_bytes_s=interconnect_bytes_s,
        energy_per_op_pj=energy_per_op_pj,
        energy_per_byte_pj=energy_per_byte_pj,
        energy_per_comm_byte_pj=energy_per_comm_byte_pj,
        area_mm2=area_mm2,
        fixed_latency_us=fixed_latency_us,
        clock_ghz=REFERENCE_CLOCK_GHZ,
        utilization=dict(zip(_WORKLOADS, utilization, strict=True)),
        overhead=dict(zip(_WORKLOADS, overhead, strict=True)),
        note=note,
    )


